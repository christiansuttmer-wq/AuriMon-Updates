/* Check modern species data, crystal level-up and quest integration. */
'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const root='app/src/main/assets/';
const src=n=>fs.readFileSync(root+n,'utf8');
const sandbox={window:{}};
vm.runInNewContext(src('pokemon_stats_151.js'),vm.createContext(sandbox));
vm.runInNewContext(src('dex.js'),sandbox);
vm.runInNewContext(src('pokemon_gen2_9.js'),sandbox);
const dex=sandbox.window.POKEDEX,stats=sandbox.window.POKEMON_BASESTATS;
assert.equal(dex.length,1025);
assert.equal(new Set(dex.map(p=>p.id)).size,1025);
assert.equal(dex[151].name,'Endivie');
assert.equal(dex[1024].name,'Infamomo');
assert.deepEqual(Array.from(dex[1024].types),['Gift','Geist']);
assert(dex.every((p,i)=>p.id===i+1&&p.types.length>0&&p.name.length>0&&Array.isArray(p.evol)));
assert(stats.slice(1,1026).every(x=>x&&x.length===6&&x.every(n=>Number.isInteger(n)&&n>0)));
assert.equal(new Set(dex.flatMap(p=>p.types)).size,18);
assert.equal(sandbox.window.AuriMonGen9.generation,undefined);
assert.equal(sandbox.window.AuriMonGen9.genenrations,undefined);
assert.equal(sandbox.window.AuriMonGen9.speciesCount,1025);
const game=src('game.js'),ui=src('aurimon_2_0.js'),html=src('index.html');
assert.match(game,/const ELEMENT_TYPES=\[/);
assert.match(game,/function ascendWithCrystal\(uid,type\)/);
assert.match(game,/if\(!POKE\[p.id\]\.types\.includes\(type\)\)/);
assert.match(game,/if\(p.xp<xpNeeded\(p.level,p.id\)\)/);
assert.match(game,/state\.bag\[id\]--/);
assert.match(game,/p\.level\+\+/);
assert.match(game,/if\(lv>=150\)return Infinity/);
assert.match(game,/p\.level<100&&p\.xp>=xpNeeded/);
assert.match(game,/EXTENDED_REGIONS\.forEach/);
assert.match(ui,/questTitles=\[/);
assert.match(ui,/if\(cmd==='ascend-open'\)/);
assert.match(ui,/if\(cmd==='epic-claim'\)/);
assert.match(html,/<script src="pokemon_gen2_9\.js"><\/script>/);
assert.match(html,/<script src="aurimon_2_0\.js"><\/script>/);
const i=html.indexOf('pokemon_gen2_9.js'),j=html.indexOf('game.js');
assert(i>0&&i<j,'New Gen9 data must load before engine');
console.log('[PASS] 1025 localized Pokemon, 18 types, 1025 stat tuples, level 150 crystal-gate and 30 new region quest hooks.');
