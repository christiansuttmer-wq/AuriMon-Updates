/* AuriMon 1.3.2 — Kampf als echtes dreigeteiltes Querformat-Layout.
   Ausführung NACH allen bisherigen Kampf-Modulen; Kampfaktionen bleiben unverändert. */
(() => {
  'use strict';
  if (typeof renderBattle !== 'function') return;

  const oldRenderBattle = renderBattle;
  function buildBattleLayout() {
    const box = document.getElementById('battle-content');
    if (!box || !battle) return;
    const top = box.querySelector('.battletop');
    const arena = box.querySelector('.arena');
    const log = box.querySelector('.battlelog');
    const actions = box.querySelector('.battleactions');
    if (!top || !arena || !actions || !log) return;

    const allySprite = arena.querySelector('.allyart');
    const enemySprite = arena.querySelector('.enemyart');
    const allyStatus = arena.querySelector('.allylabel');
    const enemyStatus = arena.querySelector('.enemylabel');
    if (!allySprite || !enemySprite || !allyStatus || !enemyStatus) return;

    box.classList.add('auri131-battle');
    const title = top.querySelector('b');
    if(title) title.textContent = title.textContent.replace(/1\.3\.0/g, '1.3.2');
    const stage = document.createElement('div'); stage.className = 'auri131-stage';
    const tools = document.createElement('section'); tools.className = 'auri131-tools'; tools.setAttribute('aria-label', 'Gegenstände und Aktionen');
    const moves = document.createElement('section'); moves.className = 'auri131-moves'; moves.setAttribute('aria-label', 'Attacken');
    const center = document.createElement('section'); center.className = 'auri131-center'; center.setAttribute('aria-label', 'Kampffeld');

    function label(text){ const el=document.createElement('h3');el.className='auri131-panel-heading';el.textContent=text;return el; }
    tools.append(label('🎒 Items & Aktionen'));
    moves.append(label('⚔️ Attacken'));
    const itemGrid = document.createElement('div'); itemGrid.className='auri131-item-grid';
    const moveGrid = document.createElement('div'); moveGrid.className='auri131-move-grid';
    const buttons=Array.from(actions.querySelectorAll('button'));
    for (const button of buttons) {
      // Move buttons are generated by the existing move and PP system.
      if (/^(?:move|attack):/.test(button.dataset.battle || '')) moveGrid.append(button);
      else itemGrid.append(button);
    }
    if (!itemGrid.children.length) {
      const hint=document.createElement('p');hint.className='auri131-empty';hint.textContent='Keine Gegenstände verfügbar.';itemGrid.append(hint);
    }
    tools.append(itemGrid); moves.append(moveGrid);
    actions.remove();

    const fighters = document.createElement('div'); fighters.className = 'auri131-fighters';
    function createFighter(team, sprite, status) {
      const fighter = document.createElement('div'); fighter.className = 'auri131-fighter ' + team;
      fighter.append(sprite, status); // Anzeige STETS unmittelbar unter dem eigenen AuriMon.
      return fighter;
    }
    fighters.append(createFighter('ally', allySprite, allyStatus));
    fighters.append(createFighter('enemy', enemySprite, enemyStatus));
    arena.append(fighters);

    center.append(arena, log);
    stage.append(tools, center, moves);
    box.replaceChildren(top, stage);
  }
  renderBattle = function (...args) {
    const value = oldRenderBattle.apply(this, args);
    buildBattleLayout();
    return value;
  };
  document.querySelector('.brand span')?.replaceChildren(document.createTextNode('20 ORTE · 151 AURIMON · VERSION 1.3.2'));
})();
